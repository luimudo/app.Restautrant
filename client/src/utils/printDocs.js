// Formatos impresos generados por el servidor: ticket termico de 80 mm (HTML) y A4 (PDF).
// Mismo esquema que DistribucionBebidas: el fetch lleva el token de sesion y no se abren rutas publicas.

const download = async (path) => {
    const res = await fetch(path);
    if (!res.ok) {
        const body = await res.json().catch(() => ({}));
        throw new Error(body.error || 'No se pudo generar el documento.');
    }
    return res;
};

/** Opens the A4 PDF in a new tab. The window is opened first so the browser does not block it as a popup. */
export const abrirPdf = async (path) => {
    const win = window.open('', '_blank');
    try {
        const blob = await (await download(path)).blob();
        const url = URL.createObjectURL(blob);
        if (win) win.location.href = url; else window.location.assign(url);
        setTimeout(() => URL.revokeObjectURL(url), 60000);
    } catch (error) {
        win?.close();
        throw error;
    }
};

/** Downloads the generated PDF with the series and correlativo supplied by the API. */
export const descargarPdf = async (path) => {
    const res = await download(path);
    const disposition = res.headers.get('content-disposition') || '';
    const utf8Name = disposition.match(/filename\*\s*=\s*UTF-8''([^;]+)/i)?.[1];
    const quotedName = disposition.match(/filename\s*=\s*"([^"]+)"/i)?.[1];
    const plainName = disposition.match(/filename\s*=\s*([^;]+)/i)?.[1];
    let filename = utf8Name || quotedName || plainName || 'Comprobante.pdf';
    try { filename = decodeURIComponent(filename.trim()); } catch { filename = filename.trim(); }

    const url = URL.createObjectURL(await res.blob());
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 60000);
};

// Chrome names the "Save as PDF" file after the title of the PAGE that calls print(), not the one of the iframe.
// While the print dialog is open the page takes the document title (series and correlativo) and gets its own back afterwards.
let tituloPagina = null;
const tomarTitulo = (titulo) => {
    if (!titulo) return () => {};
    if (tituloPagina === null) tituloPagina = document.title;
    document.title = titulo;
    let restaurado = false;
    const restaurar = () => {
        if (restaurado) return;
        restaurado = true;
        if (tituloPagina !== null) document.title = tituloPagina;
        tituloPagina = null;
    };
    // Safety net: some browsers never fire afterprint.
    setTimeout(restaurar, 120000);
    return restaurar;
};

/** Prints an 80 mm ticket from a hidden iframe: no extra windows and no scripts in the document. */
export const imprimirHtml = (html) => {
    const frame = document.createElement('iframe');
    const documento = new DOMParser().parseFromString(html, 'text/html');
    const titulo = documento.title?.trim();
    if (titulo) {
        frame.title = titulo;
        frame.name = titulo;
    }
    frame.setAttribute('aria-hidden', 'true');
    frame.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0;visibility:hidden';
    frame.onload = () => {
        setTimeout(() => {
            const impresion = frame.contentWindow;
            if (titulo && frame.contentDocument) frame.contentDocument.title = titulo;
            const restaurar = tomarTitulo(titulo);
            const terminar = () => { restaurar(); setTimeout(() => frame.remove(), 500); };
            impresion.addEventListener('afterprint', terminar, { once: true });
            impresion.focus();
            try {
                impresion.print();
            } catch (error) {
                terminar();
                throw error;
            }
        }, 150);
    };
    frame.srcdoc = html;
    document.body.appendChild(frame);
};

export const imprimirTicket = async (path) => imprimirHtml(await (await download(path)).text());

/** Pre-cuenta of the table, generated by the server with the company data. */
export const imprimirPreCuenta = async (mesa, items) => {
    const res = await fetch('/api/precuenta/ticket', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ mesa, items })
    });
    if (!res.ok) {
        const body = await res.json().catch(() => ({}));
        throw new Error(body.error || 'No se pudo generar la pre-cuenta.');
    }
    imprimirHtml(await res.text());
};

